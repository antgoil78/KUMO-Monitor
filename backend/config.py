# An unset selector preserves the split deployment during migration. Once set,
# every application-owned object must belong to the selected environment.
ENVIRONMENT = os.getenv("KUMO_ENV", "").strip().upper()
if ENVIRONMENT and ENVIRONMENT not in ("DEV", "TST"):
    raise ValueError("KUMO_ENV must be DEV or TST (or unset during migration)")
ENVIRONMENT_DATABASE = f"KUMO_{ENVIRONMENT}" if ENVIRONMENT else None


def _setting(name, default):
    return os.getenv(name, "").strip() or default


# Deployment identity can differ from the DEV/TST database selector on future
# UAT/PROD accounts. It labels the service and never changes data routing.
DEPLOYMENT_ENVIRONMENT = _setting("KUMO_DEPLOYMENT_ENV", ENVIRONMENT).upper()
DEPLOYMENT_ENVIRONMENT = {"TST": "TEST", "PRD": "PROD"}.get(DEPLOYMENT_ENVIRONMENT, DEPLOYMENT_ENVIRONMENT)
if DEPLOYMENT_ENVIRONMENT and DEPLOYMENT_ENVIRONMENT not in ("DEV", "TEST", "UAT", "PROD"):
    raise ValueError("KUMO_DEPLOYMENT_ENV must be DEV, TEST, UAT or PROD")


def _identifier(name, default):
    value = _setting(name, default)
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", value):
        raise ValueError(f"{name} must be an unquoted Snowflake identifier")
    return value.upper()


def _database(name, default):
    value = _identifier(name, default)
    if ENVIRONMENT_DATABASE and value != ENVIRONMENT_DATABASE:
        raise ValueError(f"{name} must be {ENVIRONMENT_DATABASE} when KUMO_ENV={ENVIRONMENT}")
    return value


def _object(name, default):
    value = _setting(name, default)
    if ENVIRONMENT_DATABASE:
        parts = value.split(".")
        if len(parts) != 3 or not all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", p) for p in parts):
            raise ValueError(f"{name} must be an unquoted database.schema.object name")
        if parts[0].upper() != ENVIRONMENT_DATABASE:
            raise ValueError(f"{name} must belong to {ENVIRONMENT_DATABASE} when KUMO_ENV={ENVIRONMENT}")
    return value


