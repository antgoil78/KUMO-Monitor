-- PROCEDURE KUMO_DEV.MONITOR_APP.SP_RULE_BASED_WORKFLOW_REQUEST_RUN
CREATE PROCEDURE KUMO_DEV.MONITOR_APP.SP_RULE_BASED_WORKFLOW_REQUEST_RUN("P_PARENT_RUN_ID" VARCHAR, "P_EVALUATE_WORKFLOW_ID" VARCHAR, "P_DATABASE" VARCHAR DEFAULT 'KUMO_DEV')
RETURNS TABLE ()
LANGUAGE SQL
EXECUTE AS CALLER
AS 'DECLARE
  E_INVALID_DATABASE EXCEPTION (-20002, ''Invalid database identifier'');
BEGIN
  LET V_DATABASE VARCHAR := UPPER(TRIM(P_DATABASE));
  IF (V_DATABASE IS NULL OR NOT REGEXP_LIKE(V_DATABASE, ''^[A-Z_][A-Z0-9_$]*$'')) THEN
    RAISE E_INVALID_DATABASE;
  END IF;
 

let monitorSchema := V_DATABASE || ''.MONITOR_META'';
let appSchema := V_DATABASE || ''.MONITOR_APP'';
let metaSchema := V_DATABASE || ''.META'';
let procName varchar := appSchema || ''.SP_WORKFLOW_REQUEST_RUN'';

let sql := 
    ''with data as (
        select 
            r.workflow_id,
            
            r.dependee_type dependee_type,
            nvl(coalesce(wf_dep.workflow_id,m_dep.model_name),r.dependee_id) dependee_name,
            
            iff(r.success,''''|SUCCESS'''','''''''')||iff(r.warning,''''|WARNING'''','''''''')||iff(r.error,''''|ERROR'''','''''''')||''''|'''' accepted_status,
            coalesce(wf_dep.status,m_dep.status) dep_status,
            nvl(contains(accepted_status,dep_status),false) result_status,
    
            r.newer must_be_newer,
            nvl(wf.loaded_dttm,''''1901-01-01'''') as loaded_dttm,
            coalesce(wf_dep.loaded_dttm,m_dep.loaded_dttm) dep_loaded_dttm,
            case when must_be_newer
            then nvl(dep_loaded_dttm,''''1001-01-01'''') > nvl(wf.loaded_dttm,''''1901-01-01'''')
            else dep_loaded_dttm is not null end as result_must_be_newer
            
        from '' || metaSchema || ''.workflow_dep_rule r
        left outer join '' || metaSchema || ''.workflow_status wf
            on r.workflow_id = wf.workflow_id
        left outer join '' || metaSchema || ''.workflow_status wf_dep
            on r.dependee_id = wf_dep.workflow_id
            and r.dependee_type = ''''workflow''''
        left outer join '' || metaSchema || ''.model_status m_dep
            on r.dependee_id = m_dep.model_name
            and r.dependee_type = ''''model''''
        where r.active_fl
    ),
    result as (
        select
            workflow_id
        from 
            data
        group by workflow_id
        having min(least(result_status,result_must_be_newer))
    )
    
    select nvl(result.workflow_id=data.workflow_id,false) as result_ruleset,
        data.* 
    from data 
        left outer join result on data.workflow_id = result.workflow_id'';

    if (P_EVALUATE_WORKFLOW_ID is not null) then
        sql := sql || '' where data.workflow_id = '''''' || P_EVALUATE_WORKFLOW_ID || '''''''';
        sql := sql || '' order by data.workflow_id, dependee_type desc, dependee_name'';
    end if;

    let ruleResult resultset := (execute immediate sql);
    let ruleResultQid varchar := last_query_id();
    let resultLog := '''';

    if (P_EVALUATE_WORKFLOW_ID is null) then  -- Que the workflows
    
        let c1 cursor for select distinct WORKFLOW_ID
                            from table(result_scan(?)) 
                            where RESULT_RULESET;
        
        open c1 using (ruleResultQid);
        
        for wf in c1 do 
            let currentWfId varchar := wf.WORKFLOW_ID;

            call identifier(:procName)(:currentWfId, ''DEPENDENCY_RULE'', null, null, :P_PARENT_RUN_ID);
            let runId varchar(36) := (select $1 from table(result_scan(last_query_id())));

            resultLog := resultLog || ''Rule for workflow '''' ||
(select WORKFLOW_NAME from '' || monitorSchema || ''.WORKFLOWS where WORKFLOW_ID = '''''' || currentWfId || '''''') || '''' evaulated true, run requested as run_id '' || runId || ''\\n'';

        end for;
        close c1;
    
    end if;

    if (resultLog != '''') then
        sql := ''update '' || monitorSchema || ''.WORKFLOW_HISTORY '';
        sql := sql || ''set PAYLOAD_MESSAGE = '''''' || resultLog || '''''' '';
        sql := sql || ''where RUN_ID = '''''' || P_PARENT_RUN_ID || '''''''';
    else
        sql := ''update '' || monitorSchema || ''.WORKFLOW_HISTORY '';
        sql := sql || ''set PAYLOAD_MESSAGE = ''''No rules evaluated true, nothing to do'''''';
        sql := sql || ''where RUN_ID = '''''' || P_PARENT_RUN_ID || '''''''';
    end if;
    execute immediate sql;

    let retVal resultset := (select * exclude (WORKFLOW_ID) from table(result_scan(:ruleResultQid)));
    return table(retval);

end';

-- PROCEDURE KUMO_DEV.MONITOR_APP.SP_RUN_WORKFLOW
CREATE PROCEDURE KUMO_DEV.MONITOR_APP.SP_RUN_WORKFLOW("P_WORKFLOW_ID" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_DATABASE VARCHAR DEFAULT CURRENT_DATABASE();
  V_PAYLOAD VARIANT;
  V_RUN_ID STRING;
  V_SQL STRING;

  V_CHAIN_ID STRING;
  V_CHAIN_DEPTH NUMBER;

  V_ON_SUCCESS_RAW VARIANT;
  V_ON_FAIL_RAW VARIANT;

  V_PENDING_CNT NUMBER;
  V_IS_DBT BOOLEAN DEFAULT FALSE;

  V_TASK_NAME STRING;
  V_TASK_DDL STRING;
  V_RUN_ID_ESC STRING;

  V_NEXT_SAFE VARIANT;
  V_CHILD_WF_ID STRING;
  V_EXIST_CNT NUMBER;

  V_MAX_DEPTH NUMBER DEFAULT 20;
  V_CLAIM_TS TIMESTAMP_NTZ;

  RS_CHILDREN RESULTSET;

  E_DISPATCH_NOT_OK EXCEPTION (-20001, ''SP_WORKFLOW_DISPATCH returned ok=false'');
BEGIN
  V_CLAIM_TS := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

  /*
    Important:
    The master dispatcher may already have claimed the run and moved it from
    QUEUED -> DISPATCHING.

    Therefore, do not create a new run just because no row is currently QUEUED.
  */
  SELECT COUNT(*)
    INTO :V_PENDING_CNT
  FROM MONITOR_META.WORKFLOW_RUN_QUEUE
  WHERE TRIM(WORKFLOW_ID) = TRIM(:P_WORKFLOW_ID)
    AND UPPER(TRIM(STATUS)) IN (''QUEUED'', ''DISPATCHING'');

  /*
    If there is no queued/dispatching run, this is a direct/manual invocation.
    Create a new run request, then immediately claim one QUEUED row as DISPATCHING.
  */
  IF (V_PENDING_CNT = 0) THEN
    CALL MONITOR_APP.SP_WORKFLOW_REQUEST_RUN(
      :P_WORKFLOW_ID,
      ''SCHEDULE'',
      NULL,
      NULL,
      NULL
    );
  END IF;

  /*
    Claim exactly one QUEUED row for this workflow when this proc is called directly.

    When called from the master dispatcher, the row should already be DISPATCHING,
    so this update will normally affect zero rows.
  */
  UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
     SET STATUS     = ''DISPATCHING'',
         CLAIMED_AT = COALESCE(CLAIMED_AT, :V_CLAIM_TS),
         CLAIMED_BY = COALESCE(CLAIMED_BY, ''SP_RUN_WORKFLOW'')
   WHERE RUN_ID IN (
     SELECT RUN_ID
     FROM MONITOR_META.WORKFLOW_RUN_QUEUE
     WHERE TRIM(WORKFLOW_ID) = TRIM(:P_WORKFLOW_ID)
       AND UPPER(TRIM(STATUS)) = ''QUEUED''
     ORDER BY REQUESTED_AT, RUN_ID
     LIMIT 1
   );

  /*
    This procedure now expects SP_WORKFLOW_DISPATCH to be compatible with
    DISPATCHING rows, not only QUEUED rows.
  */
  CALL MONITOR_APP.SP_WORKFLOW_DISPATCH(:P_WORKFLOW_ID);

  SELECT $1::VARIANT
    INTO :V_PAYLOAD
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  IF (COALESCE(V_PAYLOAD:ok::BOOLEAN, FALSE)) THEN
    V_RUN_ID       := V_PAYLOAD:run_id::STRING;
    V_SQL          := V_PAYLOAD:exec_sql::STRING;
    V_CHAIN_ID     := V_PAYLOAD:chain_id::STRING;
    V_CHAIN_DEPTH  := V_PAYLOAD:chain_depth::NUMBER;

    IF (V_CHAIN_ID IS NULL OR TRIM(V_CHAIN_ID) = '''') THEN
      V_CHAIN_ID := V_RUN_ID;
    END IF;

    IF (V_CHAIN_DEPTH IS NULL) THEN
      V_CHAIN_DEPTH := 0;
    END IF;

    V_ON_SUCCESS_RAW := V_PAYLOAD:on_success;
    V_ON_FAIL_RAW    := V_PAYLOAD:on_fail;

    INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
      (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES
      (:V_RUN_ID, ''INFO'', ''SP_RUN: dispatch ok'');

    /*
      The workflow has now been selected for execution.
      Move it out of DISPATCHING so it cannot be picked up again.
    */
    UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
       SET STATUS = ''DISPATCHED''
     WHERE RUN_ID = :V_RUN_ID
       AND UPPER(TRIM(STATUS)) IN (''QUEUED'', ''CLAIMED'', ''STARTING'', ''DISPATCHING'');

    V_IS_DBT := (UPPER(TRIM(:V_SQL)) LIKE ''EXECUTE DBT PROJECT%'');

    V_TASK_NAME :=
      :V_DATABASE || ''.MONITOR_APP.TMP_WF_'' || REPLACE(:V_RUN_ID, ''-'', ''_'');

    V_RUN_ID_ESC := REPLACE(:V_RUN_ID, '''''''', '''''''''''');

    IF (V_IS_DBT) THEN
      V_TASK_DDL :=
        ''CREATE OR REPLACE TASK '' || :V_TASK_NAME ||
        '' WAREHOUSE = KUMO_ELT_GEN_1'' ||
        '' SCHEDULE = ''''USING CRON 0 0 29 2 * UTC'''''' ||
        '' USER_TASK_TIMEOUT_MS = 21600000'' ||
        '' AS DECLARE V_ERR STRING; BEGIN'' ||
        ''   USE DATABASE "'' || :V_DATABASE || ''"; USE SCHEMA RAW_LIM;'' ||
        ''   '' || :V_SQL || '';'' ||
        ''   CALL MONITOR_APP.SP_DBT_COMPLETE('''''' || :V_RUN_ID_ESC || '''''', TRUE);'' ||
        '' EXCEPTION WHEN OTHER THEN'' ||
        ''   V_ERR := SQLERRM;'' ||
        ''   CALL MONITOR_APP.SP_DBT_COMPLETE('''''' || :V_RUN_ID_ESC || '''''', FALSE, :V_ERR);'' ||
        '' END'';
    ELSE
      V_TASK_DDL :=
        ''CREATE OR REPLACE TASK '' || :V_TASK_NAME ||
        '' WAREHOUSE = KUMO_ELT_GEN_1'' ||
        '' SCHEDULE = ''''USING CRON 0 0 29 2 * UTC'''''' ||
        '' USER_TASK_TIMEOUT_MS = 21600000'' ||
        '' AS DECLARE V_ERR STRING; BEGIN'' ||
        ''   USE DATABASE "'' || :V_DATABASE || ''"; USE SCHEMA RAW_LIM;'' ||
        ''   '' || :V_SQL || '';'' ||
        ''   CALL MONITOR_APP.SP_SQL_COMPLETE('''''' || :V_RUN_ID_ESC || '''''', TRUE);'' ||
        '' EXCEPTION WHEN OTHER THEN'' ||
        ''   V_ERR := SQLERRM;'' ||
        ''   CALL MONITOR_APP.SP_SQL_COMPLETE('''''' || :V_RUN_ID_ESC || '''''', FALSE, :V_ERR);'' ||
        '' END'';
    END IF;

    /*
      Create temporary execution task.
    */
    BEGIN
      EXECUTE IMMEDIATE :V_TASK_DDL;

      BEGIN
        MERGE INTO MONITOR_META.WORKFLOW_TMP_TASKS t
        USING (
          SELECT
            :V_RUN_ID AS RUN_ID,
            :P_WORKFLOW_ID AS WORKFLOW_ID,
            :V_TASK_NAME AS TASK_FQN,
            SPLIT_PART(:V_TASK_NAME, ''.'', 3) AS TASK_NAME
        ) s
        ON t.TASK_FQN = s.TASK_FQN

        WHEN MATCHED THEN UPDATE SET
            RUN_ID        = s.RUN_ID,
            WORKFLOW_ID   = s.WORKFLOW_ID,
            TASK_NAME     = s.TASK_NAME,
            STATUS        = ''CREATED'',
            CLEANED_AT    = NULL,
            CLEANUP_ERROR = NULL

        WHEN NOT MATCHED THEN INSERT (
            RUN_ID,
            WORKFLOW_ID,
            TASK_FQN,
            TASK_NAME,
            STATUS
        )
        VALUES (
            s.RUN_ID,
            s.WORKFLOW_ID,
            s.TASK_FQN,
            s.TASK_NAME,
            ''CREATED''
        );

      EXCEPTION
        WHEN OTHER THEN
          INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
            (RUN_ID, LOG_LEVEL, MESSAGE)
          VALUES
            (
              :V_RUN_ID,
              ''WARN'',
              ''SP_RUN: temp task registry insert failed. task='' || :V_TASK_NAME ||
              '', err='' || COALESCE(SQLERRM, ''?'')
            );
      END;

    EXCEPTION
      WHEN OTHER THEN
        INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
          (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES
          (:V_RUN_ID, ''ERROR'', ''SP_RUN: CREATE TASK failed. err='' || COALESCE(SQLERRM, ''?''));

        UPDATE MONITOR_META.WORKFLOW_HISTORY
           SET STATUS = ''FAILED'',
               END_TIME = SYSDATE(),
               ERROR_MESSAGE = ''Task creation failed: '' || COALESCE(SQLERRM, ''?''),
               UPDATED_AT = SYSDATE()
         WHERE RUN_ID = :V_RUN_ID;

        UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
           SET STATUS = ''FAILED''
         WHERE RUN_ID = :V_RUN_ID;

        BEGIN
          CALL MONITOR_APP.SP_SEND_NOTIFICATION(
            :P_WORKFLOW_ID,
            :V_RUN_ID,
            FALSE,
            ''Task creation failed: '' || COALESCE(SQLERRM, ''?'')
          );
        EXCEPTION
          WHEN OTHER THEN NULL;
        END;

        RETURN ''FAIL_CREATE_TASK'';
    END;

    /*
      Resume and fire temporary task.
    */
    BEGIN
      EXECUTE IMMEDIATE ''ALTER TASK '' || :V_TASK_NAME || '' RESUME'';
      EXECUTE IMMEDIATE ''EXECUTE TASK '' || :V_TASK_NAME;

      /*
        The async task has now been fired.
        Completion should later be handled by SP_DBT_COMPLETE or SP_SQL_COMPLETE.
      */
      UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
         SET STATUS = ''RUNNING''
       WHERE RUN_ID = :V_RUN_ID
         AND UPPER(TRIM(STATUS)) IN (''DISPATCHED'', ''DISPATCHING'', ''QUEUED'');

    EXCEPTION
      WHEN OTHER THEN
        INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
          (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES
          (:V_RUN_ID, ''ERROR'', ''SP_RUN: EXECUTE TASK failed. err='' || COALESCE(SQLERRM, ''?''));

        UPDATE MONITOR_META.WORKFLOW_HISTORY
           SET STATUS = ''FAILED'',
               END_TIME = SYSDATE(),
               ERROR_MESSAGE = ''Task execution failed: '' || COALESCE(SQLERRM, ''?''),
               UPDATED_AT = SYSDATE()
         WHERE RUN_ID = :V_RUN_ID;

        UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
           SET STATUS = ''FAILED''
         WHERE RUN_ID = :V_RUN_ID;

        BEGIN
          EXECUTE IMMEDIATE ''DROP TASK IF EXISTS '' || :V_TASK_NAME;
        EXCEPTION
          WHEN OTHER THEN NULL;
        END;

        BEGIN
          CALL MONITOR_APP.SP_SEND_NOTIFICATION(
            :P_WORKFLOW_ID,
            :V_RUN_ID,
            FALSE,
            ''Task execution failed: '' || COALESCE(SQLERRM, ''?'')
          );
        EXCEPTION
          WHEN OTHER THEN NULL;
        END;

        RETURN ''FAIL_EXECUTE_TASK'';
    END;

    INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
      (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES
      (:V_RUN_ID, ''INFO'', ''SP_RUN: fired via '' || :V_TASK_NAME);

    RETURN ''OK_ASYNC'';

  ELSE
    /*
      Do not silently return OK here.
      If the master dispatcher already moved a row to DISPATCHING, silently returning
      would let the master think dispatch succeeded.
    */
    RAISE E_DISPATCH_NOT_OK;
  END IF;

EXCEPTION
  WHEN OTHER THEN
    IF (V_RUN_ID IS NOT NULL) THEN
      INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
        (RUN_ID, LOG_LEVEL, MESSAGE)
      VALUES
        (:V_RUN_ID, ''ERROR'', ''SP_RUN: ex='' || COALESCE(SQLERRM, ''?''));

      UPDATE MONITOR_META.WORKFLOW_HISTORY
         SET STATUS = ''FAILED'',
             END_TIME = SYSDATE(),
             ERROR_MESSAGE = COALESCE(SQLERRM, ''FAIL''),
             UPDATED_AT = SYSDATE()
       WHERE RUN_ID = :V_RUN_ID;

      UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
         SET STATUS = ''FAILED''
       WHERE RUN_ID = :V_RUN_ID;
    END IF;

    RAISE;
END;
';

