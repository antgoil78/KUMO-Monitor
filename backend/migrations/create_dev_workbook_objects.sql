            TRIM(SUBSTR(rr.DATA_T, 22, 3))        AS DLVY_LIM_OBJ_SEQ_NO,
            TRIM(SUBSTR(rr.DATA_T, 25, 3))        AS DLVY_LIM_OBJ_VER_NO,
            TRIM(SUBSTR(rr.DATA_T, 10, 3))        AS DLVY_PKG_ID,
            SUBSTR(TRIM(SUBSTR(rr.DATA_T, 13, 9)), 1, 4) AS DLVY_PKG_YEAR,
