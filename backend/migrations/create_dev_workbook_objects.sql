            rr.RAW_TABLE,
            rr.FILE_NAME AS CONTROL_FILE_NAME,
            rr.FILE_KEY AS CONTROL_FILE_KEY,
            UPPER(TRIM(SUBSTR(rr.DATA_T, 3, 3)))  AS DLVY_SOURCE_ID,
