            REGEXP_SUBSTR(DW_FILE_NM::STRING, ''[^/]+$'') AS BASE_FILE_NAME,
            TRIM(DATA::STRING) AS DATA_T,
            SUBSTR(TRIM(DATA::STRING), 1, 2) AS RECORD_TYPE,
            IFNULL(DW_READY_TO_LOAD_FL, FALSE) AS DW_READY_TO_LOAD_FL
        FROM IDENTIFIER(:V_RAW_TABLE)
