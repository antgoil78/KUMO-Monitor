                COALESCE(
                    TRY_TO_DATE(SUBSTR(rr.DATA_T, 38, 10), ''YYYY-MM-DD''),
                    TRY_TO_DATE(SUBSTR(rr.DATA_T, 38, 8),  ''YYYYMMDD'')
