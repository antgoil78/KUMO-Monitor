    physical_file_status AS (
        SELECT
            RAW_TABLE,
            ORIGINAL_FILE_NAME,
            FILE_NAME,
            FILE_KEY,
            FILE_TYPE,
            DLVY_SOURCE_ID,
            DLVY_SUBJECT_AREA_ID,
            DLVY_LIM_OBJ_SEQ_NO,
            DLVY_LIM_OBJ_VER_NO,
            DLVY_PKG_ID,
            DLVY_PKG_YEAR,
            DLVY_PKG_YEAR_SEQ_NO,
            DLVY_END_DATE,
            READY_TO_LOAD_ROW_EXISTS,
            RAW_ROW_COUNT,
            HEADER_00_CNT,
            DATA_10_CNT,
            FOOTER_99_CNT,
            EXPECTED_ROWS,
