  V_RUN_ID         STRING DEFAULT UUID_STRING();
  V_QUEUE_ID       STRING DEFAULT UUID_STRING();

  V_CHAIN_ID       STRING;
  V_CHAIN_DEPTH    NUMBER;

  V_TRIGGER_SOURCE STRING;
BEGIN
  --------------------------------------------------------------------
  -- Normalize inputs into variables (avoid expressions in VALUES)
  --------------------------------------------------------------------
  V_TRIGGER_SOURCE := COALESCE(NULLIF(TRIM(:P_TRIGGER_SOURCE), ''''), ''UNKNOWN'');

  V_CHAIN_ID := COALESCE(NULLIF(TRIM(:P_CHAIN_ID), ''''), V_RUN_ID);
  V_CHAIN_DEPTH := COALESCE(:P_CHAIN_DEPTH, 0);

  --------------------------------------------------------------------
  -- 1) Insert into HISTORY (as QUEUED)
  --------------------------------------------------------------------
  INSERT INTO MONITOR_META.WORKFLOW_HISTORY (
      RUN_ID,
      WORKFLOW_ID,
      STATUS,
      REQUESTED_AT,
      REQUESTED_BY,
      TRIGGER_SOURCE,
      CHAIN_ID,
      CHAIN_DEPTH,
      PARENT_RUN_ID,
      UPDATED_AT
  )
  VALUES (
      :V_RUN_ID,
      :P_WORKFLOW_ID,
      ''QUEUED'',
      SYSDATE(),
      CURRENT_USER(),
      :V_TRIGGER_SOURCE,
      :V_CHAIN_ID,
      :V_CHAIN_DEPTH,
      :P_PARENT_RUN_ID,
      SYSDATE()
  );

  --------------------------------------------------------------------
  -- 2) Insert into RUN_QUEUE (as QUEUED)
  --------------------------------------------------------------------
  INSERT INTO MONITOR_META.WORKFLOW_RUN_QUEUE (
      QUEUE_ID,
      WORKFLOW_ID,
      RUN_ID,
      STATUS,
      REQUESTED_AT,
      REQUESTED_BY
  )
  VALUES (
      :V_QUEUE_ID,
      :P_WORKFLOW_ID,
      :V_RUN_ID,
      ''QUEUED'',
      SYSDATE(),
      CURRENT_USER()
  );

  --------------------------------------------------------------------
  -- KUMO_EXTERNAL_RUN_LOCK_TRACKING_V1
  -- Register runs from dependency rules, schedules, and external SQL.
  --------------------------------------------------------------------
  MERGE INTO MONITOR_META.APP_WORKFLOW_RUN_LOCKS t
  USING (
    SELECT
      UUID_STRING() AS LOCK_ID,
      :P_WORKFLOW_ID AS WORKFLOW_ID,
      COALESCE(w.WORKFLOW_NAME, :P_WORKFLOW_ID) AS WORKFLOW_NAME,
      :V_RUN_ID AS RUN_ID,
      CURRENT_USER() AS REQUESTED_BY
    FROM MONITOR_META.WORKFLOWS w
    WHERE w.WORKFLOW_ID = :P_WORKFLOW_ID
  ) s
  ON t.WORKFLOW_ID = s.WORKFLOW_ID
     AND t.RELEASED_AT IS NULL
     AND t.LOCK_EXPIRES_AT >= CURRENT_TIMESTAMP()
  WHEN MATCHED THEN UPDATE SET
    RUN_ID = s.RUN_ID,
    STATUS = ''QUEUED'',
    WORKFLOW_NAME = s.WORKFLOW_NAME,
    REQUESTED_BY = s.REQUESTED_BY,
    REQUESTED_BY_USER = s.REQUESTED_BY,
    LAST_SEEN_AT = CURRENT_TIMESTAMP(),
    LOCK_EXPIRES_AT = DATEADD(''minute'', 360, CURRENT_TIMESTAMP()),
    MESSAGE = ''Queued through SP_WORKFLOW_REQUEST_RUN'',
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    LOCK_ID, WORKFLOW_ID, WORKFLOW_NAME, RUN_ID, STATUS,
    REQUESTED_BY, REQUESTED_BY_USER, REQUESTED_BY_ROLE, SESSION_MODE,
    REQUESTED_AT, LAST_SEEN_AT, LOCK_EXPIRES_AT, MESSAGE, UPDATED_AT
  ) VALUES (
    s.LOCK_ID, s.WORKFLOW_ID, s.WORKFLOW_NAME, s.RUN_ID, ''QUEUED'',
    s.REQUESTED_BY, s.REQUESTED_BY, CURRENT_ROLE(), ''SNOWFLAKE_SQL'',
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(),
    DATEADD(''minute'', 360, CURRENT_TIMESTAMP()),
    ''Queued through SP_WORKFLOW_REQUEST_RUN'', CURRENT_TIMESTAMP()
  );

  RETURN V_RUN_ID;
END;
';

-- STAGE KUMO_DEV.META.AZURE_LIM_STAGE
CREATE STAGE KUMO_DEV.META.AZURE_LIM_STAGE CLONE KUMO_TST.META.AZURE_LIM_STAGE;

-- STREAM KUMO_DEV.MONITOR_META.WORKFLOW_EXECUTION_QUEUE_STREAM
CREATE stream KUMO_DEV.MONITOR_META.WORKFLOW_EXECUTION_QUEUE_STREAM on table KUMO_DEV.MONITOR_META.WORKFLOW_RUN_QUEUE append_only = true;

-- TASK KUMO_DEV.MONITOR_APP.TASK_WF_MASTER_DISPATCHER
CREATE task KUMO_DEV.MONITOR_APP.TASK_WF_MASTER_DISPATCHER
	warehouse=KUMO_ELT_GEN_1
	when SYSTEM$STREAM_HAS_DATA('KUMO_DEV.MONITOR_META.WORKFLOW_EXECUTION_QUEUE_STREAM')
	as DECLARE
  V_CLAIM_TS    TIMESTAMP_NTZ;
  V_CLAIM_USER  STRING;
  V_WORKFLOW_ID STRING;
  V_RUN_ID      STRING;
  V_ERROR       STRING;
BEGIN
  V_CLAIM_TS   := CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;
  V_CLAIM_USER := CURRENT_USER();

  /*
    Consume the stream into a temp table.

    Keep all stream rows for diagnostics/filtering, but only use QUEUED insert
    rows as dispatch candidates.

    This CTAS advances the stream offset.
  */
  CREATE OR REPLACE TEMPORARY TABLE TMP_STREAM_CONSUMED AS
  SELECT
      RUN_ID,
      WORKFLOW_ID,
      STATUS,
      METADATA$ACTION   AS STREAM_ACTION,
      METADATA$ISUPDATE AS STREAM_ISUPDATE
  FROM MONITOR_META.WORKFLOW_EXECUTION_QUEUE_STREAM;

  /*
    Candidate rows are rows whose new state is QUEUED.

    This includes:
    - fresh inserts into the queue
    - updates/requeues where the new version is QUEUED
  */
  CREATE OR REPLACE TEMPORARY TABLE TMP_QUEUE_CANDIDATES AS
  SELECT DISTINCT RUN_ID
  FROM TMP_STREAM_CONSUMED
  WHERE STREAM_ACTION = 'INSERT'
    AND UPPER(TRIM(STATUS)) = 'QUEUED'
    AND RUN_ID IS NOT NULL;

  /*
    Claim only candidate queue rows.
  */
  UPDATE KUMO_DEV.MONITOR_META.WORKFLOW_RUN_QUEUE Q
     SET STATUS     = 'DISPATCHING',
         CLAIMED_AT = :V_CLAIM_TS,
         CLAIMED_BY = :V_CLAIM_USER
   WHERE UPPER(TRIM(Q.STATUS)) = 'QUEUED'
     AND EXISTS (
       SELECT 1
       FROM TMP_QUEUE_CANDIDATES S
       WHERE S.RUN_ID = Q.RUN_ID
     );

  /*
    Process only rows claimed by this task invocation.
  */
  LET RS RESULTSET := (
    SELECT WORKFLOW_ID, RUN_ID
    FROM KUMO_DEV.MONITOR_META.WORKFLOW_RUN_QUEUE
    WHERE UPPER(TRIM(STATUS)) = 'DISPATCHING'
      AND CLAIMED_AT = :V_CLAIM_TS
      AND CLAIMED_BY = :V_CLAIM_USER
    ORDER BY REQUESTED_AT, RUN_ID
    LIMIT 10
  );

  FOR REC IN RS DO
    V_WORKFLOW_ID := REC.WORKFLOW_ID;
    V_RUN_ID      := REC.RUN_ID;

    INSERT INTO KUMO_DEV.MONITOR_META.WORKFLOW_RUN_LOGS
      (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES
      (:V_RUN_ID, 'INFO', 'MASTER: calling SP_RUN_WORKFLOW for ' || :V_WORKFLOW_ID);

    BEGIN
      CALL MONITOR_APP.SP_RUN_WORKFLOW(:V_WORKFLOW_ID, :V_RUN_ID);

      /*
        Do not set STATUS = DISPATCHED here.

        SP_RUN_WORKFLOW should move:
          DISPATCHING -> DISPATCHED -> RUNNING

        The master only claims and invokes.
      */
      INSERT INTO KUMO_DEV.MONITOR_META.WORKFLOW_RUN_LOGS
        (RUN_ID, LOG_LEVEL, MESSAGE)
      VALUES
        (:V_RUN_ID, 'INFO', 'MASTER: SP_RUN_WORKFLOW completed for ' || :V_WORKFLOW_ID);

    EXCEPTION
      WHEN OTHER THEN
        V_ERROR := SQLERRM;

        /*
          Only requeue if the row is still owned by this task invocation and has not
          already moved forward inside SP_RUN_WORKFLOW.
        */
        UPDATE KUMO_DEV.MONITOR_META.WORKFLOW_RUN_QUEUE
           SET STATUS = 'QUEUED'
         WHERE RUN_ID = :V_RUN_ID
           AND UPPER(TRIM(STATUS)) = 'DISPATCHING'
           AND CLAIMED_AT = :V_CLAIM_TS
           AND CLAIMED_BY = :V_CLAIM_USER;

        INSERT INTO KUMO_DEV.MONITOR_META.WORKFLOW_RUN_LOGS
          (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES
          (
            :V_RUN_ID,
            'ERROR',
            'MASTER: failed ' || :V_WORKFLOW_ID || ' err=' || COALESCE(:V_ERROR, '?')
          );
    END;
  END FOR;
END;
