        FROM physical_file_agg
    ),
    control_files AS (
        SELECT
            RAW_TABLE,
            ORIGINAL_FILE_NAME,
            FILE_NAME,
            FILE_KEY,
            FILE_NAME AS CONTROL_FILE_NAME,
            ''CONTROL'' AS FILE_TYPE,
            FALSE AS EXPECTED_BY_CONTROL_FL,
            TRUE AS RECEIVED_FL,
            READY_STATUS,
            ROWCOUNT_STATUS,
            FILE_EXISTS_IN_RAW,
            DW_READY_TO_LOAD_FL,
            DLVY_SOURCE_ID,
            DLVY_SUBJECT_AREA_ID,
            DLVY_LIM_OBJ_SEQ_NO,
            DLVY_LIM_OBJ_VER_NO,
            DLVY_PKG_ID,
            DLVY_PKG_YEAR,
            DLVY_PKG_YEAR_SEQ_NO,
            DLVY_END_DATE,
            EXPECTED_ROWS,
            DATA_ROWS,
            ACTUAL_ROWS
