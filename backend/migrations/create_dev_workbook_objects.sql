-- PROCEDURE KUMO_DEV.MONITOR_APP.SP_SQL_COMPLETE
CREATE PROCEDURE KUMO_DEV.MONITOR_APP.SP_SQL_COMPLETE("P_RUN_ID" VARCHAR, "P_SUCCESS" BOOLEAN, "P_ERROR_MSG" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_WF_ID STRING; V_CHAIN_ID STRING; V_CHAIN_DEPTH NUMBER; V_SKIP_CHILDREN BOOLEAN DEFAULT FALSE;
  V_ON_RAW VARIANT; V_NEXT_SAFE VARIANT;
  V_CHILD_WF_ID STRING; V_EXIST_CNT NUMBER; V_MAX_DEPTH NUMBER DEFAULT 20;
  RS_CHILDREN RESULTSET;
BEGIN
  IF (:P_SUCCESS) THEN
    UPDATE MONITOR_META.WORKFLOW_HISTORY SET STATUS=''SUCCESS'', END_TIME=SYSDATE(), UPDATED_AT=SYSDATE() WHERE RUN_ID=:P_RUN_ID;
  ELSE
    UPDATE MONITOR_META.WORKFLOW_HISTORY SET STATUS=''FAILED'', END_TIME=SYSDATE(), ERROR_MESSAGE=COALESCE(:P_ERROR_MSG,''SQL_FAILED''), UPDATED_AT=SYSDATE() WHERE RUN_ID=:P_RUN_ID;
  END IF;
  UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE SET STATUS=''DONE'' WHERE RUN_ID=:P_RUN_ID;
  INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
  VALUES (:P_RUN_ID, IFF(:P_SUCCESS,''INFO'',''ERROR''), ''SQL_COMPLETE: '' || IFF(:P_SUCCESS,''SUCCESS'',''FAILED: '' || COALESCE(:P_ERROR_MSG,''?'')));

  SELECT WORKFLOW_ID, CHAIN_ID, CHAIN_DEPTH, COALESCE(SKIP_CHILDREN, FALSE) INTO :V_WF_ID, :V_CHAIN_ID, :V_CHAIN_DEPTH, :V_SKIP_CHILDREN
  FROM MONITOR_META.WORKFLOW_HISTORY WHERE RUN_ID=:P_RUN_ID;
  IF (V_CHAIN_ID IS NULL OR TRIM(V_CHAIN_ID)='''') THEN V_CHAIN_ID := :P_RUN_ID; END IF;
  IF (V_CHAIN_DEPTH IS NULL) THEN V_CHAIN_DEPTH := 0; END IF;

  -- Send notification
  BEGIN
    CALL MONITOR_APP.SP_SEND_NOTIFICATION(:V_WF_ID, :P_RUN_ID, :P_SUCCESS, :P_ERROR_MSG);
  EXCEPTION WHEN OTHER THEN NULL;
  END;

  IF (V_SKIP_CHILDREN) THEN
    INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES (:P_RUN_ID, ''INFO'', ''COMPLETE: child workflows skipped for this run'');
    RETURN ''OK'';
  END IF;

  IF (:P_SUCCESS) THEN
    SELECT COALESCE(ON_SUCCESS, PARSE_JSON(''[]'')) INTO :V_ON_RAW FROM MONITOR_META.WORKFLOW_TASKS WHERE WORKFLOW_ID=:V_WF_ID;
  ELSE
    SELECT COALESCE(ON_FAIL, PARSE_JSON(''[]'')) INTO :V_ON_RAW FROM MONITOR_META.WORKFLOW_TASKS WHERE WORKFLOW_ID=:V_WF_ID;
  END IF;
  SELECT CASE WHEN :V_ON_RAW IS NULL THEN PARSE_JSON(''[]'') WHEN TYPEOF(:V_ON_RAW)=''ARRAY'' THEN :V_ON_RAW ELSE ARRAY_CONSTRUCT(TO_VARCHAR(:V_ON_RAW)) END INTO :V_NEXT_SAFE;
  IF (COALESCE(V_CHAIN_DEPTH,0) < V_MAX_DEPTH) THEN
    LET RS_CHILDREN RESULTSET := (SELECT TRIM(VALUE::STRING) AS CID FROM TABLE(FLATTEN(INPUT=>:V_NEXT_SAFE)) WHERE VALUE IS NOT NULL AND TRIM(VALUE::STRING)<>'''' AND UPPER(TRIM(VALUE::STRING))<>''NOTHING'');
    FOR REC IN RS_CHILDREN DO
      V_CHILD_WF_ID := REC.CID;
      SELECT COUNT(*) INTO :V_EXIST_CNT FROM MONITOR_META.WORKFLOW_HISTORY WHERE CHAIN_ID=:V_CHAIN_ID AND WORKFLOW_ID=:V_CHILD_WF_ID;
      IF (V_EXIST_CNT=0) THEN
        INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES (:P_RUN_ID, ''INFO'', ''SQL_COMPLETE: chain '' || IFF(:P_SUCCESS,''on_success'',''on_fail'') || '' -> '' || :V_CHILD_WF_ID);
        CALL MONITOR_APP.SP_WORKFLOW_REQUEST_RUN(:V_CHILD_WF_ID, IFF(:P_SUCCESS,''ON_SUCCESS'',''ON_FAIL''), :V_CHAIN_ID, COALESCE(:V_CHAIN_DEPTH,0)+1, :P_RUN_ID);
        BEGIN CALL MONITOR_APP.SP_RUN_WORKFLOW(:V_CHILD_WF_ID); EXCEPTION WHEN OTHER THEN
          INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE) VALUES (:P_RUN_ID, ''ERROR'', ''SQL_COMPLETE: child failed '' || :V_CHILD_WF_ID); END;
      END IF;
    END FOR;
  END IF;
  RETURN ''OK'';
END
';

-- PROCEDURE KUMO_DEV.MONITOR_APP.SP_WORKFLOW_DISPATCH
CREATE PROCEDURE KUMO_DEV.MONITOR_APP.SP_WORKFLOW_DISPATCH("P_WORKFLOW_ID" VARCHAR)
RETURNS VARIANT
LANGUAGE JAVASCRIPT
EXECUTE AS OWNER
AS '
function escMsg(s) {
  return (s === null || s === undefined) ? "" : String(s);
}

function log(runId, level, msg) {
  snowflake.execute({
    sqlText: `
      INSERT INTO MONITOR_META.WORKFLOW_RUN_LOGS
        (RUN_ID, LOG_LEVEL, MESSAGE)
      VALUES (?, ?, ?)
    `,
    binds: [runId, level, msg]
  });
}

function oneRow(sqlText, binds) {
  const rs = snowflake.execute({
    sqlText: sqlText,
    binds: binds || []
  });

  if (rs.next()) {
    const obj = {};
    for (let i = 1; i <= rs.getColumnCount(); i++) {
      obj[rs.getColumnName(i)] = rs.getColumnValue(i);
    }
    return obj;
  }

  return null;
}

function isSafeProjectFqn(fqn) {
  if (!fqn) return false;

  const parts = String(fqn).trim().split(".");
  if (parts.length !== 3) return false;

  const allowed = ''ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_.$"'';

  for (const p of parts) {
    if (!p || !String(p).trim()) return false;

    for (let i = 0; i < p.length; i++) {
      if (allowed.indexOf(p[i]) === -1) return false;
    }
  }

  return true;
}

function markFailedAndDone(runId, msg) {
  snowflake.execute({
    sqlText: `
      UPDATE MONITOR_META.WORKFLOW_HISTORY
         SET STATUS = ''FAILED'',
             START_TIME = COALESCE(START_TIME, SYSDATE()),
             END_TIME = SYSDATE(),
             ERROR_MESSAGE = ?,
             UPDATED_AT = SYSDATE()
       WHERE RUN_ID = ?
    `,
    binds: [msg, runId]
  });

  /*
    Kept as DONE to preserve your existing behavior.
    If you have adopted FAILED as a queue terminal state everywhere,
    change this to STATUS = ''FAILED''.
  */
  snowflake.execute({
    sqlText: `
      UPDATE MONITOR_META.WORKFLOW_RUN_QUEUE
         SET STATUS = ''DONE''
       WHERE RUN_ID = ?
    `,
    binds: [runId]
  });
}

function trimTrailingSemicolons(s) {
  let x = String(s || "").trim();
  while (x.endsWith(";")) {
    x = x.slice(0, -1).trim();
  }
  return x;
}

function normalizeHook(v) {
  if (v === null || v === undefined) return [];
  if (Array.isArray(v)) return v;

  const s = String(v).trim();
  if (!s) return [];

  return [s];
}

/*
  Load workflow and task hooks.
*/
const wf = oneRow(
  `
    SELECT
        w.WORKFLOW_ID,
        w.WORKFLOW_NAME,
        COALESCE(w.WORKFLOW_TYPE, ''DBT'') AS WORKFLOW_TYPE,
        w.DBT_COMMAND,
        w.SQL_COMMAND,
        w.IS_ENABLED,
        COALESCE(w.DBT_TARGET, '''') AS DBT_TARGET,
        COALESCE(w.DBT_PROJECT_FQN, '''') AS DBT_PROJECT_FQN,
        t.ON_SUCCESS AS ON_SUCCESS,
        t.ON_FAIL    AS ON_FAIL
     FROM MONITOR_META.WORKFLOWS w
     LEFT JOIN MONITOR_META.WORKFLOW_TASKS t
       ON t.WORKFLOW_ID = w.WORKFLOW_ID
    WHERE w.WORKFLOW_ID = ?
  `,
  [P_WORKFLOW_ID]
);

if (!wf) {
  return {
    ok: false,
    reason: "WORKFLOW_NOT_FOUND",
    workflow_id: String(P_WORKFLOW_ID)
  };
}

const workflowType = String(wf.WORKFLOW_TYPE || "DBT").trim().toUpperCase();
const wtype = (workflowType === "SQL" || workflowType === "DBT") ? workflowType : "DBT";

/*
  Claim/dispatch one queue row.

  Important:
  - DISPATCHING is preferred because the master dispatcher already claimed it.
  - QUEUED allows direct/manual calls to SP_RUN_WORKFLOW.
  - STARTING is retained as a legacy compatibility state.
  - CLAIMED is intentionally not used anymore.
*/
let claimed = null;

for (let attempt = 0; attempt < 5; attempt++) {
  const cand = oneRow(
    `
      SELECT
          QUEUE_ID,
          RUN_ID,
          STATUS,
          CHAIN_ID,
          CHAIN_DEPTH,
          PARENT_RUN_ID,
          DBT_COMMAND_OVERRIDE
       FROM MONITOR_META.WORKFLOW_RUN_QUEUE
      WHERE TRIM(WORKFLOW_ID) = TRIM(?)
        AND UPPER(TRIM(STATUS)) IN (''DISPATCHING'', ''QUEUED'', ''STARTING'')
      ORDER BY
        CASE UPPER(TRIM(STATUS))
          WHEN ''DISPATCHING'' THEN 1
          WHEN ''QUEUED''      THEN 2
          WHEN ''STARTING''    THEN 3
          ELSE 9
        END,
        REQUESTED_AT,
        RUN_ID
      LIMIT 1
    `,
    [P_WORKFLOW_ID]
  );

  if (!cand) {
    return {
