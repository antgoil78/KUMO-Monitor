create or replace TABLE KUMO_ADMIN.WORKFLOW_MANAGER.EMAIL_GROUPS (
	GROUP_NAME VARCHAR(16777216) NOT NULL,
	RECIPIENTS VARCHAR(16777216) NOT NULL,
	DESCRIPTION VARCHAR(16777216) DEFAULT '',
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CAST(CONVERT_TIMEZONE('UTC', CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_TZ(9))) AS TIMESTAMP_NTZ(9)),
