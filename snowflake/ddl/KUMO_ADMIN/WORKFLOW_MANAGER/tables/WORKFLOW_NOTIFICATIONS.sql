USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

create or replace TABLE KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_NOTIFICATIONS (
	WORKFLOW_ID VARCHAR(16777216) NOT NULL,
	ON_SUCCESS_EMAIL BOOLEAN DEFAULT FALSE,
	ON_FAIL_EMAIL BOOLEAN DEFAULT TRUE,
	SUCCESS_RECIPIENTS VARCHAR(16777216) DEFAULT '',
	FAIL_RECIPIENTS VARCHAR(16777216) DEFAULT '',
	EMAIL_INTEGRATION VARCHAR(16777216) DEFAULT 'MY_EMAIL_INT',
	ENVIRONMENT VARCHAR(16777216) DEFAULT 'PROD',
	UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CAST(CONVERT_TIMEZONE('UTC', CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_TZ(9))) AS TIMESTAMP_NTZ(9)),
	SUCCESS_GROUP VARCHAR(16777216) DEFAULT '',
	FAIL_GROUP VARCHAR(16777216) DEFAULT '',
	primary key (WORKFLOW_ID)
);
