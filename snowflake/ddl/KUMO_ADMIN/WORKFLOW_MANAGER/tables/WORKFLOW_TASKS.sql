USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

create or replace TABLE KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_TASKS (
	WORKFLOW_ID VARCHAR(36) NOT NULL,
	SCHEDULE_CRON VARCHAR(100) NOT NULL,
	SCHEDULE_TIMEZONE VARCHAR(64) NOT NULL DEFAULT 'UTC',
	ON_SUCCESS VARIANT,
	ON_FAIL VARIANT,
	IS_ENABLED BOOLEAN DEFAULT TRUE,
	UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	UPDATED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
	NEXT_SCHEDULE_TS TIMESTAMP_NTZ(9),
	LAST_SCHEDULE_TS TIMESTAMP_NTZ(9),
	constraint PK_WORKFLOW_TASKS primary key (WORKFLOW_ID),
	constraint FK_TASKS_WORKFLOW foreign key (WORKFLOW_ID) references KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOWS(WORKFLOW_ID)
);
