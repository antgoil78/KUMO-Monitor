USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

create or replace TABLE KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY (
	RUN_ID VARCHAR(36) NOT NULL DEFAULT UUID_STRING(),
	WORKFLOW_ID VARCHAR(36) NOT NULL,
	STATUS VARCHAR(20),
	TRIGGER_SOURCE VARCHAR(20) DEFAULT 'MANUAL',
	REQUESTED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
	REQUESTED_AT TIMESTAMP_NTZ(9) DEFAULT CAST(CONVERT_TIMEZONE('UTC', CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_TZ(9))) AS TIMESTAMP_NTZ(9)),
	START_TIME TIMESTAMP_NTZ(9),
	END_TIME TIMESTAMP_NTZ(9),
	ERROR_MESSAGE VARCHAR(16777216),
	DBT_INVOCATION_ID VARCHAR(128),
	ENGINE_TASK_NAME VARCHAR(500),
	ENGINE_QUERY_ID VARCHAR(50),
	UPDATED_AT TIMESTAMP_NTZ(9),
	DBT_ARGS VARCHAR(16777216),
	DBT_QUERY_ID VARCHAR(16777216),
	DBT_EXEC_COMMAND VARCHAR(16777216),
	CHAIN_ID VARCHAR(16777216),
	CHAIN_DEPTH NUMBER(38,0),
	PARENT_RUN_ID VARCHAR(16777216),
	SKIP_CHILDREN BOOLEAN DEFAULT FALSE,
	PAYLOAD_MESSAGE VARCHAR(16777216),
	constraint PK_WORKFLOW_HISTORY primary key (RUN_ID),
	constraint FK_HISTORY_WORKFLOW foreign key (WORKFLOW_ID) references KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOWS(WORKFLOW_ID)
);
