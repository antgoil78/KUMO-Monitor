USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

create or replace view KUMO_ADMIN.WORKFLOW_MANAGER.V_WORKFLOW_MONITOR(
	WORKFLOW_ID,
	WORKFLOW_GROUP,
	WORKFLOW_NAME,
	DESCRIPTION,
	DBT_COMMAND,
	WORKFLOW_ENABLED,
	SCHEDULE_CRON,
	SCHEDULE_TIMEZONE,
	TASK_ENABLED,
	LAST_RUN_ID,
	LAST_STATUS,
	LAST_START_TIME,
	LAST_END_TIME,
	LAST_DURATION_SECONDS
) as
WITH LAST_RUN AS (
  SELECT
    WORKFLOW_ID,
    RUN_ID,
    STATUS,
    START_TIME,
    END_TIME
  FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY WORKFLOW_ID
    ORDER BY COALESCE(START_TIME, REQUESTED_AT) DESC
  ) = 1
)
SELECT
  w.WORKFLOW_ID,
  w.WORKFLOW_GROUP,
  w.WORKFLOW_NAME,
  w.DESCRIPTION,
  w.DBT_COMMAND,
  w.IS_ENABLED AS WORKFLOW_ENABLED,

  t.SCHEDULE_CRON,
  t.SCHEDULE_TIMEZONE,
  t.IS_ENABLED AS TASK_ENABLED,

  h.RUN_ID      AS LAST_RUN_ID,
  h.STATUS      AS LAST_STATUS,
  h.START_TIME  AS LAST_START_TIME,
  h.END_TIME    AS LAST_END_TIME,
  DATEDIFF('second', h.START_TIME, h.END_TIME) AS LAST_DURATION_SECONDS
FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOWS w
LEFT JOIN KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_TASKS t
  ON t.WORKFLOW_ID = w.WORKFLOW_ID
LEFT JOIN LAST_RUN h
  ON h.WORKFLOW_ID = w.WORKFLOW_ID
ORDER BY w.WORKFLOW_NAME;
