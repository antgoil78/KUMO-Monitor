USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

CREATE OR REPLACE PROCEDURE KUMO_ADMIN.WORKFLOW_MANAGER.X_SP_SCHEDULER_GUARD("WF_ID" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_WORKFLOW_ID STRING DEFAULT wf_id;
  V_ALREADY_Q   NUMBER;
  V_RUNNING     NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO :V_ALREADY_Q
  FROM  KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_QUEUE q
  WHERE q.WORKFLOW_ID = :V_WORKFLOW_ID
    AND UPPER(TRIM(q.STATUS)) IN (''QUEUED'',''STARTING'',''CLAIMED'');

  SELECT COUNT(*)
    INTO :V_RUNNING
  FROM  KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY h
  WHERE h.WORKFLOW_ID = :V_WORKFLOW_ID
    AND UPPER(TRIM(h.STATUS)) = ''RUNNING'';

  IF (V_ALREADY_Q = 0 AND V_RUNNING = 0) THEN
    CALL  KUMO_ADMIN.WORKFLOW_MANAGER.SP_WORKFLOW_REQUEST_RUN(
      :V_WORKFLOW_ID,
      ''SCHEDULE'',
      NULL, NULL, NULL
    );
  END IF;

  RETURN ''OKfff'';
END
';
