-- Refresh: python snowflake/export_ddl.py
USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

CREATE OR REPLACE PROCEDURE KUMO_ADMIN.WORKFLOW_MANAGER.SP_SEND_NOTIFICATION("P_WORKFLOW_ID" VARCHAR, "P_RUN_ID" VARCHAR, "P_SUCCESS" BOOLEAN, "P_ERROR_MSG" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_ON_EMAIL BOOLEAN;
    V_GROUP_NAME VARCHAR;
    V_RECIPIENTS VARCHAR;
    V_INTEGRATION VARCHAR;
    V_ENVIRONMENT VARCHAR;
    V_WF_NAME VARCHAR;
    V_WF_GROUP VARCHAR;
    V_SEVERITY VARCHAR;
    V_EVENT_TYPE VARCHAR;
    V_ERR VARCHAR;
BEGIN
    IF (:P_SUCCESS) THEN
        SELECT n.ON_SUCCESS_EMAIL, n.SUCCESS_GROUP, n.EMAIL_INTEGRATION, n.ENVIRONMENT
          INTO :V_ON_EMAIL, :V_GROUP_NAME, :V_INTEGRATION, :V_ENVIRONMENT
        FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_NOTIFICATIONS n
        WHERE n.WORKFLOW_ID = :P_WORKFLOW_ID;
    ELSE
        SELECT n.ON_FAIL_EMAIL, n.FAIL_GROUP, n.EMAIL_INTEGRATION, n.ENVIRONMENT
          INTO :V_ON_EMAIL, :V_GROUP_NAME, :V_INTEGRATION, :V_ENVIRONMENT
        FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_NOTIFICATIONS n
        WHERE n.WORKFLOW_ID = :P_WORKFLOW_ID;
    END IF;

    IF (V_ON_EMAIL IS NULL OR NOT V_ON_EMAIL) THEN
        RETURN ''SKIP_NOT_CONFIGURED'';
    END IF;
    IF (V_GROUP_NAME IS NULL OR TRIM(V_GROUP_NAME) = '''') THEN
        RETURN ''SKIP_NO_GROUP'';
    END IF;

    SELECT RECIPIENTS INTO :V_RECIPIENTS
    FROM KUMO_ADMIN.WORKFLOW_MANAGER.EMAIL_GROUPS
    WHERE GROUP_NAME = :V_GROUP_NAME;

    IF (V_RECIPIENTS IS NULL OR TRIM(V_RECIPIENTS) = '''') THEN
        RETURN ''SKIP_EMPTY_GROUP'';
    END IF;

    SELECT WORKFLOW_NAME, WORKFLOW_GROUP
      INTO :V_WF_NAME, :V_WF_GROUP
    FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOWS
    WHERE WORKFLOW_ID = :P_WORKFLOW_ID;

    V_SEVERITY := IFF(:P_SUCCESS, ''SUCCESS'', ''ERROR'');
    V_EVENT_TYPE := IFF(:P_SUCCESS, ''WORKFLOW_SUCCESS'', ''WORKFLOW_FAILED'');

    CALL KUMO_ADMIN.WORKFLOW_MANAGER.SP_SEND_WORKFLOW_EMAIL(
        :V_INTEGRATION, :V_RECIPIENTS, :V_ENVIRONMENT, :V_SEVERITY,
        :P_RUN_ID, :V_WF_GROUP, NULL, :V_WF_NAME, ''WORKFLOW'', :V_EVENT_TYPE,
        SYSDATE(), 0,
        PARSE_JSON(OBJECT_CONSTRUCT(
            ''workflow_name'', :V_WF_NAME, ''workflow_group'', :V_WF_GROUP,
            ''status'', IFF(:P_SUCCESS, ''SUCCESS'', ''FAILED''),
            ''error_message'', :P_ERROR_MSG, ''run_id'', :P_RUN_ID
        )::VARCHAR)
    );

    INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES (:P_RUN_ID, ''INFO'', ''NOTIFICATION: '' || :V_SEVERITY || '' email sent to group '' || :V_GROUP_NAME);

    RETURN ''SENT'';

EXCEPTION
    WHEN OTHER THEN
        V_ERR := SQLERRM;
        INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES (:P_RUN_ID, ''ERROR'', ''NOTIFICATION: failed. err='' || COALESCE(:V_ERR, ''?''));
        RETURN ''ERROR: '' || COALESCE(:V_ERR, ''unknown'');
END
';
