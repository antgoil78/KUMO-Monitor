-- Refresh: python snowflake/export_ddl.py
USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

CREATE OR REPLACE PROCEDURE KUMO_ADMIN.WORKFLOW_MANAGER.SP_SQL_COMPLETE("P_RUN_ID" VARCHAR, "P_SUCCESS" BOOLEAN, "P_ERROR_MSG" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_WF_ID STRING; V_CHAIN_ID STRING; V_CHAIN_DEPTH NUMBER; V_SKIP_CHILDREN BOOLEAN DEFAULT FALSE;
  V_ON_RAW VARIANT; V_NEXT_SAFE VARIANT;
  V_CHILD_WF_ID STRING; V_EXIST_CNT NUMBER; V_MAX_DEPTH NUMBER DEFAULT 20;
  RS_CHILDREN RESULTSET;
BEGIN
  IF (:P_SUCCESS) THEN
    UPDATE KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY SET STATUS=''SUCCESS'', END_TIME=SYSDATE(), UPDATED_AT=SYSDATE() WHERE RUN_ID=:P_RUN_ID;
  ELSE
    UPDATE KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY SET STATUS=''FAILED'', END_TIME=SYSDATE(), ERROR_MESSAGE=COALESCE(:P_ERROR_MSG,''SQL_FAILED''), UPDATED_AT=SYSDATE() WHERE RUN_ID=:P_RUN_ID;
  END IF;
  UPDATE KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_QUEUE SET STATUS=''DONE'' WHERE RUN_ID=:P_RUN_ID;
  INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
  VALUES (:P_RUN_ID, IFF(:P_SUCCESS,''INFO'',''ERROR''), ''SQL_COMPLETE: '' || IFF(:P_SUCCESS,''SUCCESS'',''FAILED: '' || COALESCE(:P_ERROR_MSG,''?'')));

  SELECT WORKFLOW_ID, CHAIN_ID, CHAIN_DEPTH, COALESCE(SKIP_CHILDREN, FALSE) INTO :V_WF_ID, :V_CHAIN_ID, :V_CHAIN_DEPTH, :V_SKIP_CHILDREN
  FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY WHERE RUN_ID=:P_RUN_ID;
  IF (V_CHAIN_ID IS NULL OR TRIM(V_CHAIN_ID)='''') THEN V_CHAIN_ID := :P_RUN_ID; END IF;
  IF (V_CHAIN_DEPTH IS NULL) THEN V_CHAIN_DEPTH := 0; END IF;

  -- Send notification
  BEGIN
    CALL KUMO_ADMIN.WORKFLOW_MANAGER.SP_SEND_NOTIFICATION(:V_WF_ID, :P_RUN_ID, :P_SUCCESS, :P_ERROR_MSG);
  EXCEPTION WHEN OTHER THEN NULL;
  END;

  IF (V_SKIP_CHILDREN) THEN
    INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES (:P_RUN_ID, ''INFO'', ''COMPLETE: child workflows skipped for this run'');
    RETURN ''OK'';
  END IF;

  IF (:P_SUCCESS) THEN
    SELECT COALESCE(ON_SUCCESS, PARSE_JSON(''[]'')) INTO :V_ON_RAW FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_TASKS WHERE WORKFLOW_ID=:V_WF_ID;
  ELSE
    SELECT COALESCE(ON_FAIL, PARSE_JSON(''[]'')) INTO :V_ON_RAW FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_TASKS WHERE WORKFLOW_ID=:V_WF_ID;
  END IF;
  SELECT CASE WHEN :V_ON_RAW IS NULL THEN PARSE_JSON(''[]'') WHEN TYPEOF(:V_ON_RAW)=''ARRAY'' THEN :V_ON_RAW ELSE ARRAY_CONSTRUCT(TO_VARCHAR(:V_ON_RAW)) END INTO :V_NEXT_SAFE;
  IF (COALESCE(V_CHAIN_DEPTH,0) < V_MAX_DEPTH) THEN
    LET RS_CHILDREN RESULTSET := (SELECT TRIM(VALUE::STRING) AS CID FROM TABLE(FLATTEN(INPUT=>:V_NEXT_SAFE)) WHERE VALUE IS NOT NULL AND TRIM(VALUE::STRING)<>'''' AND UPPER(TRIM(VALUE::STRING))<>''NOTHING'');
    FOR REC IN RS_CHILDREN DO
      V_CHILD_WF_ID := REC.CID;
      SELECT COUNT(*) INTO :V_EXIST_CNT FROM KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY WHERE CHAIN_ID=:V_CHAIN_ID AND WORKFLOW_ID=:V_CHILD_WF_ID;
      IF (V_EXIST_CNT=0) THEN
        INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES (:P_RUN_ID, ''INFO'', ''SQL_COMPLETE: chain '' || IFF(:P_SUCCESS,''on_success'',''on_fail'') || '' -> '' || :V_CHILD_WF_ID);
        CALL KUMO_ADMIN.WORKFLOW_MANAGER.SP_WORKFLOW_REQUEST_RUN(:V_CHILD_WF_ID, IFF(:P_SUCCESS,''ON_SUCCESS'',''ON_FAIL''), :V_CHAIN_ID, COALESCE(:V_CHAIN_DEPTH,0)+1, :P_RUN_ID);
        BEGIN CALL KUMO_ADMIN.WORKFLOW_MANAGER.SP_RUN_WORKFLOW(:V_CHILD_WF_ID); EXCEPTION WHEN OTHER THEN
          INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_LOGS (RUN_ID, LOG_LEVEL, MESSAGE) VALUES (:P_RUN_ID, ''ERROR'', ''SQL_COMPLETE: child failed '' || :V_CHILD_WF_ID); END;
      END IF;
    END FOR;
  END IF;
  RETURN ''OK'';
END
';
