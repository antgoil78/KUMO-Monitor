USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

CREATE OR REPLACE PROCEDURE KUMO_ADMIN.WORKFLOW_MANAGER.X_SP_WORKFLOW_REQUEST_RUN_2ARG("P_WORKFLOW_ID" VARCHAR, "P_TRIGGER_SOURCE" VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_RUN_ID STRING;
BEGIN
  V_RUN_ID := UUID_STRING();

  -- 1) History row (this is what your monitor should read)
  INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_HISTORY
    (RUN_ID, WORKFLOW_ID, STATUS, REQUESTED_AT, REQUESTED_BY, TRIGGER_SOURCE, UPDATED_AT)
  VALUES
    (:V_RUN_ID, :P_WORKFLOW_ID, ''QUEUED'', CURRENT_TIMESTAMP(), CURRENT_USER(), :P_TRIGGER_SOURCE, CURRENT_TIMESTAMP());

  -- 2) Queue row (this is what dispatcher claims)
  INSERT INTO KUMO_ADMIN.WORKFLOW_MANAGER.WORKFLOW_RUN_QUEUE
    (WORKFLOW_ID, RUN_ID, STATUS, TRIGGER_SOURCE, REQUESTED_AT, REQUESTED_BY)
  VALUES
    (:P_WORKFLOW_ID, :V_RUN_ID, ''QUEUED'', :P_TRIGGER_SOURCE, CURRENT_TIMESTAMP(), CURRENT_USER());

  RETURN V_RUN_ID;
END;
';
