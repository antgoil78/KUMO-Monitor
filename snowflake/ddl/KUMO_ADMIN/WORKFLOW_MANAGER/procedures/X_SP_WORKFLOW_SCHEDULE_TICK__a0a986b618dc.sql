USE DATABASE "KUMO_ADMIN";
USE SCHEMA "KUMO_ADMIN"."WORKFLOW_MANAGER";

CREATE OR REPLACE PROCEDURE KUMO_ADMIN.WORKFLOW_MANAGER.X_SP_WORKFLOW_SCHEDULE_TICK("P_WORKFLOW_ID" VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_RUN_ID   STRING;
  V_DISPATCH VARIANT;
BEGIN
  -- 1) Request run
  CALL KUMO_ADMIN.WORKFLOW_MANAGER.SP_WORKFLOW_REQUEST_RUN(:P_WORKFLOW_ID, ''SCHEDULE'');

  -- Capture returned RUN_ID from the last CALL
  SELECT $1::STRING
    INTO :V_RUN_ID
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  -- 2) Dispatch (execute dbt)
  CALL KUMO_ADMIN.WORKFLOW_MANAGER.SP_WORKFLOW_DISPATCH(:P_WORKFLOW_ID);

  -- Capture dispatcher return VARIANT
  SELECT $1::VARIANT
    INTO :V_DISPATCH
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  RETURN OBJECT_CONSTRUCT(
    ''run_id'', V_RUN_ID,
    ''dispatch'', V_DISPATCH
  );
END;
';
