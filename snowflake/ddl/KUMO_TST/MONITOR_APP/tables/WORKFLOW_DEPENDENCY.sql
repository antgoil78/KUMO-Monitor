USE DATABASE "KUMO_TST";
USE SCHEMA "KUMO_TST"."MONITOR_APP";

create or replace TABLE KUMO_TST.MONITOR_APP.WORKFLOW_DEPENDENCY (
	WORKFLOW_DEPENDENCY_ID VARCHAR(36) NOT NULL DEFAULT UUID_STRING(),
	PARENT_WORKFLOW_ID VARCHAR(36) NOT NULL,
	CHILD_WORKFLOW_ID VARCHAR(36) NOT NULL,
	MIN_STATUS_LEVEL VARCHAR(50) NOT NULL DEFAULT 'SUCCESS',
	DEPENDENCY_TYPE VARCHAR(50) NOT NULL DEFAULT 'TRIGGER',
	IS_ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
	CREATED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP(),
	CREATED_BY VARCHAR(255) NOT NULL DEFAULT CURRENT_USER(),
	UPDATED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP(),
	UPDATED_BY VARCHAR(255) NOT NULL DEFAULT CURRENT_USER(),
	constraint UQ_MONITOR_WORKFLOW_DEPENDENCY unique (PARENT_WORKFLOW_ID, CHILD_WORKFLOW_ID),
	constraint PK_MONITOR_WORKFLOW_DEPENDENCY primary key (WORKFLOW_DEPENDENCY_ID),
	constraint FK_MONITOR_WF_DEP_PARENT foreign key (PARENT_WORKFLOW_ID) references KUMO_TST.MONITOR_APP.WORKFLOW(WORKFLOW_ID),
	constraint FK_MONITOR_WF_DEP_CHILD foreign key (CHILD_WORKFLOW_ID) references KUMO_TST.MONITOR_APP.WORKFLOW(WORKFLOW_ID)
)COMMENT='Status-aware relationships between workflows'
;
