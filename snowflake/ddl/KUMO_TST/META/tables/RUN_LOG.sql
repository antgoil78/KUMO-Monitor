USE DATABASE "KUMO_TST";
USE SCHEMA "KUMO_TST"."META";

create or replace HYBRID TABLE KUMO_TST.META.RUN_LOG (
	LOG_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 order,
	LOG_DTTM TIMESTAMP_NTZ(9) DEFAULT CAST(CONVERT_TIMEZONE('UTC', CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_TZ(9))) AS TIMESTAMP_NTZ(9)),
	RUN_ID VARCHAR(36) NOT NULL,
	DBT_INVOCATION_ID VARCHAR(256),
	ORIGIN VARCHAR(256),
	TYPE VARCHAR(256),
	MESSAGE VARCHAR(16777216),
	primary key (RUN_ID, LOG_ID)
);
