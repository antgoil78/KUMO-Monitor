USE DATABASE "KUMO_TST";
USE SCHEMA "KUMO_TST"."META";

create or replace HYBRID TABLE KUMO_TST.META.WORKFLOW_ORCHESTRATION (
	WORKFLOW_ID VARCHAR(256) NOT NULL,
	RUN_ID VARCHAR(36),
	RUN_STATUS VARCHAR(32) NOT NULL DEFAULT 'IDLE',
	CHAIN_RUN_ID VARCHAR(36),
	CHAIN_GENERATION NUMBER(38,0),
	REQUESTED_AT TIMESTAMP_NTZ(9),
	STARTED_AT TIMESTAMP_NTZ(9),
	FINISHED_AT TIMESTAMP_NTZ(9),
	ERROR_MESSAGE VARCHAR(16777216),
	TRIGGER_TYPE VARCHAR(32),
	TRIGGERED_BY_WORKFLOW_ID VARCHAR(256),
	TRIGGERED_BY_RUN_ID VARCHAR(36),
	UPSTREAM_WORKFLOW_IDS ARRAY NOT NULL DEFAULT ARRAY_CONSTRUCT(),
	DOWNSTREAM_WORKFLOW_IDS ARRAY NOT NULL DEFAULT ARRAY_CONSTRUCT(),
	CHAIN_ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
	REQUIRED_UPSTREAM_STATUS VARCHAR(32) NOT NULL DEFAULT 'SUCCESS',
	CLAIMED_BY VARCHAR(256),
	CLAIMED_AT TIMESTAMP_NTZ(9),
	CLAIM_EXPIRES_AT TIMESTAMP_NTZ(9),
	STATE_VERSION NUMBER(38,0) NOT NULL DEFAULT 0,
	CREATED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CAST(CONVERT_TIMEZONE('UTC', CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_TZ(9))) AS TIMESTAMP_NTZ(9)),
	UPDATED_AT TIMESTAMP_NTZ(9) NOT NULL DEFAULT CAST(CONVERT_TIMEZONE('UTC', CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_TZ(9))) AS TIMESTAMP_NTZ(9)),
	primary key (WORKFLOW_ID)
);
