-- Refresh: python snowflake/export_ddl.py --object PROCEDURE 'KUMO_DEV.MONITOR_APP.SP_SQL_COMPLETE(VARCHAR, BOOLEAN, VARCHAR)'
USE DATABASE "KUMO_DEV";
USE SCHEMA "KUMO_DEV"."MONITOR_APP";

CREATE OR REPLACE PROCEDURE KUMO_DEV.MONITOR_APP.SP_SQL_COMPLETE("P_RUN_ID" VARCHAR, "P_SUCCESS" BOOLEAN, "P_ERROR_MSG" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  V_ENV VARIANT;
  E_META_SCHEMA_WORKFLOW_HISTORY VARCHAR;
  E_META_SCHEMA_WORKFLOW_RUN_LOGS VARCHAR;
  E_META_SCHEMA_WORKFLOW_RUN_QUEUE VARCHAR;
  E_META_SCHEMA_WORKFLOW_TASKS VARCHAR;
  E_MONITOR_APP_SCHEMA_SP_RUN_WORKFLOW VARCHAR;
  E_MONITOR_APP_SCHEMA_SP_SEND_NOTIFICATION VARCHAR;
  E_MONITOR_APP_SCHEMA_SP_WORKFLOW_REQUEST_RUN VARCHAR;

  V_WF_ID STRING; V_CHAIN_ID STRING; V_CHAIN_DEPTH NUMBER; V_SKIP_CHILDREN BOOLEAN DEFAULT FALSE;
  V_ON_RAW VARIANT; V_NEXT_SAFE VARIANT;
  V_CHILD_WF_ID STRING; V_EXIST_CNT NUMBER; V_MAX_DEPTH NUMBER DEFAULT 20;
  RS_CHILDREN RESULTSET;
BEGIN
  CALL KUMO_DEV.MONITOR_META.SP_GET_ENVIRONMENT() INTO :V_ENV;
  E_META_SCHEMA_WORKFLOW_HISTORY := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:META_SCHEMA::VARCHAR || ''.WORKFLOW_HISTORY'';
  E_META_SCHEMA_WORKFLOW_RUN_LOGS := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:META_SCHEMA::VARCHAR || ''.WORKFLOW_RUN_LOGS'';
  E_META_SCHEMA_WORKFLOW_RUN_QUEUE := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:META_SCHEMA::VARCHAR || ''.WORKFLOW_RUN_QUEUE'';
  E_META_SCHEMA_WORKFLOW_TASKS := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:META_SCHEMA::VARCHAR || ''.WORKFLOW_TASKS'';
  E_MONITOR_APP_SCHEMA_SP_RUN_WORKFLOW := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:MONITOR_APP_SCHEMA::VARCHAR || ''.SP_RUN_WORKFLOW'';
  E_MONITOR_APP_SCHEMA_SP_SEND_NOTIFICATION := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:MONITOR_APP_SCHEMA::VARCHAR || ''.SP_SEND_NOTIFICATION'';
  E_MONITOR_APP_SCHEMA_SP_WORKFLOW_REQUEST_RUN := V_ENV:DATABASE::VARCHAR || ''.'' || V_ENV:MONITOR_APP_SCHEMA::VARCHAR || ''.SP_WORKFLOW_REQUEST_RUN'';

  IF (:P_SUCCESS) THEN
    UPDATE IDENTIFIER(:E_META_SCHEMA_WORKFLOW_HISTORY) SET STATUS=''SUCCESS'', END_TIME=SYSDATE(), UPDATED_AT=SYSDATE() WHERE RUN_ID=:P_RUN_ID;
  ELSE
    UPDATE IDENTIFIER(:E_META_SCHEMA_WORKFLOW_HISTORY) SET STATUS=''FAILED'', END_TIME=SYSDATE(), ERROR_MESSAGE=COALESCE(:P_ERROR_MSG,''SQL_FAILED''), UPDATED_AT=SYSDATE() WHERE RUN_ID=:P_RUN_ID;
  END IF;
  UPDATE IDENTIFIER(:E_META_SCHEMA_WORKFLOW_RUN_QUEUE) SET STATUS=''DONE'' WHERE RUN_ID=:P_RUN_ID;
  INSERT INTO IDENTIFIER(:E_META_SCHEMA_WORKFLOW_RUN_LOGS) (RUN_ID, LOG_LEVEL, MESSAGE)
  VALUES (:P_RUN_ID, IFF(:P_SUCCESS,''INFO'',''ERROR''), ''SQL_COMPLETE: '' || IFF(:P_SUCCESS,''SUCCESS'',''FAILED: '' || COALESCE(:P_ERROR_MSG,''?'')));

  SELECT WORKFLOW_ID, CHAIN_ID, CHAIN_DEPTH, COALESCE(SKIP_CHILDREN, FALSE) INTO :V_WF_ID, :V_CHAIN_ID, :V_CHAIN_DEPTH, :V_SKIP_CHILDREN
  FROM IDENTIFIER(:E_META_SCHEMA_WORKFLOW_HISTORY) WHERE RUN_ID=:P_RUN_ID;
  IF (V_CHAIN_ID IS NULL OR TRIM(V_CHAIN_ID)='''') THEN V_CHAIN_ID := :P_RUN_ID; END IF;
  IF (V_CHAIN_DEPTH IS NULL) THEN V_CHAIN_DEPTH := 0; END IF;

  -- Send notification
  BEGIN
    CALL IDENTIFIER(:E_MONITOR_APP_SCHEMA_SP_SEND_NOTIFICATION)(:V_WF_ID, :P_RUN_ID, :P_SUCCESS, :P_ERROR_MSG);
  EXCEPTION WHEN OTHER THEN NULL;
  END;

  IF (V_SKIP_CHILDREN) THEN
    INSERT INTO IDENTIFIER(:E_META_SCHEMA_WORKFLOW_RUN_LOGS) (RUN_ID, LOG_LEVEL, MESSAGE)
    VALUES (:P_RUN_ID, ''INFO'', ''COMPLETE: child workflows skipped for this run'');
    RETURN ''OK'';
  END IF;

  IF (:P_SUCCESS) THEN
    SELECT COALESCE(ON_SUCCESS, PARSE_JSON(''[]'')) INTO :V_ON_RAW FROM IDENTIFIER(:E_META_SCHEMA_WORKFLOW_TASKS) WHERE WORKFLOW_ID=:V_WF_ID;
  ELSE
    SELECT COALESCE(ON_FAIL, PARSE_JSON(''[]'')) INTO :V_ON_RAW FROM IDENTIFIER(:E_META_SCHEMA_WORKFLOW_TASKS) WHERE WORKFLOW_ID=:V_WF_ID;
  END IF;
  SELECT CASE WHEN :V_ON_RAW IS NULL THEN PARSE_JSON(''[]'') WHEN TYPEOF(:V_ON_RAW)=''ARRAY'' THEN :V_ON_RAW ELSE ARRAY_CONSTRUCT(TO_VARCHAR(:V_ON_RAW)) END INTO :V_NEXT_SAFE;
  IF (COALESCE(V_CHAIN_DEPTH,0) < V_MAX_DEPTH) THEN
    LET RS_CHILDREN RESULTSET := (SELECT TRIM(VALUE::STRING) AS CID FROM TABLE(FLATTEN(INPUT=>:V_NEXT_SAFE)) WHERE VALUE IS NOT NULL AND TRIM(VALUE::STRING)<>'''' AND UPPER(TRIM(VALUE::STRING))<>''NOTHING'');
    FOR REC IN RS_CHILDREN DO
      V_CHILD_WF_ID := REC.CID;
      SELECT COUNT(*) INTO :V_EXIST_CNT FROM IDENTIFIER(:E_META_SCHEMA_WORKFLOW_HISTORY) WHERE CHAIN_ID=:V_CHAIN_ID AND WORKFLOW_ID=:V_CHILD_WF_ID;
      IF (V_EXIST_CNT=0) THEN
        INSERT INTO IDENTIFIER(:E_META_SCHEMA_WORKFLOW_RUN_LOGS) (RUN_ID, LOG_LEVEL, MESSAGE)
        VALUES (:P_RUN_ID, ''INFO'', ''SQL_COMPLETE: chain '' || IFF(:P_SUCCESS,''on_success'',''on_fail'') || '' -> '' || :V_CHILD_WF_ID);
        CALL IDENTIFIER(:E_MONITOR_APP_SCHEMA_SP_WORKFLOW_REQUEST_RUN)(:V_CHILD_WF_ID, IFF(:P_SUCCESS,''ON_SUCCESS'',''ON_FAIL''), :V_CHAIN_ID, COALESCE(:V_CHAIN_DEPTH,0)+1, :P_RUN_ID);
        BEGIN CALL IDENTIFIER(:E_MONITOR_APP_SCHEMA_SP_RUN_WORKFLOW)(:V_CHILD_WF_ID); EXCEPTION WHEN OTHER THEN
          INSERT INTO IDENTIFIER(:E_META_SCHEMA_WORKFLOW_RUN_LOGS) (RUN_ID, LOG_LEVEL, MESSAGE) VALUES (:P_RUN_ID, ''ERROR'', ''SQL_COMPLETE: child failed '' || :V_CHILD_WF_ID); END;
      END IF;
    END FOR;
  END IF;
  RETURN ''OK'';
END
';
