-- Source: KUMO_DEV.MONITOR_APP.V_ORCH_WORKFLOW_RELATIONS
-- Workflow-only parents and grandparents; job sequencing is excluded.
CREATE OR REPLACE VIEW KUMO_DEV.MONITOR_APP.V_ORCH_WORKFLOW_RELATIONS
    (WORKFLOW_ID, PARENT_ID, UPSTREAM_WORKFLOW_ID, DEPTH)
AS
WITH workflow_rules AS (
    SELECT DISTINCT WORKFLOW_ID, PARENT_ID
    FROM KUMO_DEV.MONITOR_META.DEPENDENCIES
    WHERE JOB_ID IS NULL AND PARENT_ID IS NOT NULL
)
SELECT WORKFLOW_ID, PARENT_ID, PARENT_ID, 1 FROM workflow_rules
UNION
SELECT child.WORKFLOW_ID, child.PARENT_ID, parent.PARENT_ID, 2
FROM workflow_rules child
JOIN workflow_rules parent ON parent.WORKFLOW_ID = child.PARENT_ID;
