-- Source: KUMO_DEV.MONITOR_META.WORKFLOW_EXECUTION_LOG
-- Parallel orchestration state. Workflow rows are the durable queue; job rows
-- share WORKFLOW_RUN_ID and never have their own Snowflake task.
CREATE TABLE IF NOT EXISTS KUMO_DEV.MONITOR_META.WORKFLOW_EXECUTION_LOG (
    EXECUTION_ID VARCHAR(36) NOT NULL,
    WORKFLOW_RUN_ID VARCHAR(36) NOT NULL,
    WORKFLOW_ID VARCHAR(36) NOT NULL,
    JOB_ID VARCHAR(36),
    PARENT_EXECUTION_ID VARCHAR(36),
    REQUEST_ID VARCHAR(128) NOT NULL,
    RUN_MODE VARCHAR(20) NOT NULL,
    REQUESTED_JOB_ID VARCHAR(36),
    TRIGGER_SOURCE VARCHAR(30) NOT NULL DEFAULT 'MANUAL',
    STATUS VARCHAR(20) NOT NULL,
    JOB_POSITION NUMBER(9,0),
    REQUESTED_BY VARCHAR(256) NOT NULL,
    REQUESTED_AT TIMESTAMP_NTZ NOT NULL DEFAULT SYSDATE(),
    STARTED_AT TIMESTAMP_NTZ,
    ENDED_AT TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT SYSDATE(),
    CLAIM_TOKEN VARCHAR(36),
    CLAIMED_AT TIMESTAMP_NTZ,
    HEARTBEAT_AT TIMESTAMP_NTZ,
    TASK_FQN VARCHAR(500) NOT NULL,
    TASK_RUN_GROUP_ID VARCHAR(100),
    TASK_SCHEDULED_AT TIMESTAMP_LTZ,
    QUERY_ID VARCHAR(100),
    CONFIG_SNAPSHOT VARIANT NOT NULL,
    ERROR_CODE VARCHAR(100),
    ERROR_MESSAGE VARCHAR,
    RESULT VARIANT,
    CONSTRAINT PK_WORKFLOW_EXECUTION_LOG PRIMARY KEY (EXECUTION_ID)
) COMMENT='KUMO parallel orchestration v1: durable workflow requests and workflow/job results; no legacy engine state';
