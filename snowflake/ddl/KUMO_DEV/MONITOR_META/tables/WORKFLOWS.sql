USE DATABASE "KUMO_DEV";
USE SCHEMA "KUMO_DEV"."MONITOR_META";

create or replace TABLE KUMO_DEV.MONITOR_META.WORKFLOWS (
	WORKFLOW_ID VARCHAR(36) NOT NULL DEFAULT UUID_STRING(),
	WORKFLOW_NAME VARCHAR(200) NOT NULL,
	WORKFLOW_GROUP VARCHAR(200) NOT NULL,
	DESCRIPTION VARCHAR(1000),
	DBT_COMMAND VARCHAR(4000) NOT NULL,
	IS_ENABLED BOOLEAN DEFAULT TRUE,
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	CREATED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
	UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	UPDATED_BY VARCHAR(256) DEFAULT CURRENT_USER(),
	DBT_TARGET VARCHAR(16777216),
	DBT_WORKSPACE VARCHAR(16777216),
	DBT_PROJECT_FQN VARCHAR(16777216),
	WORKFLOW_TYPE VARCHAR(200),
	SQL_COMMAND VARCHAR(16777216),
	constraint UQ_WORKFLOW_NAME unique (WORKFLOW_GROUP, WORKFLOW_NAME),
	constraint PK_WORKFLOWS primary key (WORKFLOW_ID)
);
