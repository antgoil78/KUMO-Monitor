USE DATABASE "KUMO_DEV";
USE SCHEMA "KUMO_DEV"."MONITOR_META";

create or replace HYBRID TABLE KUMO_DEV.MONITOR_META.APPLICATION_PARAMETERS (
	INSTANCE_NAME VARCHAR(100) NOT NULL DEFAULT 'DEFAULT',
	PARAMETER_GROUP VARCHAR(30) NOT NULL,
	PARAMETER_KEY VARCHAR(256) NOT NULL,
	PARAMETER_VALUE VARCHAR(16777216),
	VALUE_TYPE VARCHAR(30) NOT NULL DEFAULT 'STRING',
	DESCRIPTION VARCHAR(16777216),
	IS_SECRET BOOLEAN NOT NULL DEFAULT FALSE,
	ACTIVE_FL BOOLEAN NOT NULL DEFAULT TRUE,
	CREATED_DTTM TIMESTAMP_NTZ(9) NOT NULL DEFAULT CURRENT_TIMESTAMP(),
