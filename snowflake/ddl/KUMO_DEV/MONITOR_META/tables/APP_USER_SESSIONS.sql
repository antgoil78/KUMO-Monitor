USE DATABASE "KUMO_DEV";
USE SCHEMA "KUMO_DEV"."MONITOR_META";

create or replace TABLE KUMO_DEV.MONITOR_META.APP_USER_SESSIONS (
	USER_NAME VARCHAR(16777216) NOT NULL,
	DISPLAY_NAME VARCHAR(16777216),
	FIRST_NAME VARCHAR(16777216),
	LAST_NAME VARCHAR(16777216),
	ROLE_NAME VARCHAR(16777216),
	WAREHOUSE_NAME VARCHAR(16777216),
	SESSION_MODE VARCHAR(16777216),
	CALLER_RIGHTS_ACTIVE BOOLEAN,
	CALLER_TOKEN_PRESENT BOOLEAN,
	FIRST_SEEN_AT TIMESTAMP_LTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	LAST_SEEN_AT TIMESTAMP_LTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	LAST_INTERACTION_AT TIMESTAMP_LTZ(9),
	LAST_ACTION VARCHAR(16777216),
	HIT_COUNT NUMBER(38,0) DEFAULT 0,
	CLIENT_IP VARCHAR(16777216),
	USER_AGENT VARCHAR(16777216),
	EXTRA VARIANT,
	UPDATED_AT TIMESTAMP_LTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	constraint PK_APP_USER_SESSIONS primary key (USER_NAME)
)COMMENT='KUMO Monitor durable application user/session registry. One row per Snowflake user, updated whenever the app sees the user.'
;
