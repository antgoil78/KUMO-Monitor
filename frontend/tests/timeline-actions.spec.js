import { test, expect } from './timeline.fixture.js'

test('run actions open the selected execution and preserve monitor context', async ({ page, timeline }) => {
  const { wfId, sql, dbt, currentId, shortId, monitor, requests } = timeline
  const wf = monitor.rows[0]
  monitor.rows.push(...Array.from({length:18},(_,i)=>({...wf,WORKFLOW_ID:`filler-${i}`,WORKFLOW_NAME:`Other workflow ${i}`,run:{status:'NOT RUN'},lastRun:{status:'NOT RUN'},jobs:[],progress:{total:0,succeeded:0,failed:0,skipped:0}})))
  await page.goto('/?page=orchestrationMonitor&view=timeline')
  await expect(page.locator('.ot-window')).toContainText('displayed')
  await page.getByRole('button',{name:'Expand all',exact:true}).click()
  const shortBar=()=>page.locator('[data-execution-id="short-dbt"]')
  await shortBar().click()
  const dialog=()=>page.getByRole('dialog',{name:'Run actions',exact:true})
  await expect(dialog()).toBeVisible()
  const box=await dialog().locator('.ot-run-dialog').boundingBox()
  if(box.y<0 || box.y+box.height>1121) throw Error('Run actions are not immediately in the visible viewport')
  for(const action of ['View log','Show DAG run','Execution history','Preview DAG','Zoom to execution','Trace relations','Copy run ID','Copy execution ID','Edit workflow','Dependencies','Workflow controls']) await expect(dialog().getByRole('button',{name:action,exact:true})).toBeVisible()
  await dialog().getByRole('button',{name:'Copy run ID',exact:true}).click()
  await expect.poll(()=>page.evaluate(()=>window.copiedId)).toBe(shortId)
  await dialog().getByRole('button',{name:'Copy execution ID',exact:true}).click()
  await expect.poll(()=>page.evaluate(()=>window.copiedId)).toBe('short-dbt')
  await page.keyboard.press('Escape')
  await expect(dialog()).toHaveCount(0)
  await expect(shortBar()).toBeFocused()
  await page.getByRole('button',{name:'Live',exact:true}).click()
  await page.getByLabel('Timeline zoom',{exact:true}).selectOption('43200000')
  await page.getByLabel('Search workflows, groups or jobs',{exact:true}).fill('PYMT')
  await page.getByLabel('Filter workflow group',{exact:true}).selectOption('LOAD')
  await shortBar().click()
  const x=await page.locator('.ot-viewport').evaluate(node=>node.scrollLeft)
  await dialog().getByRole('button',{name:'View log',exact:true}).click()
  await expect(page.locator('.execution-log-page')).toBeVisible()
  let request=requests.filter(req=>req.path.endsWith('/log')).at(-1)
  if(request.query.runId!==shortId || request.query.jobId!==dbt) throw Error('Log opened the latest run rather than selected run')
  const logs=requests.filter(req=>req.path.endsWith('/log')).length
  await page.clock.fastForward(6000)
  if(requests.filter(req=>req.path.endsWith('/log')).length!==logs) throw Error('Completed run log polled automatically')
  await page.getByRole('button',{name:'← Back',exact:true}).click()
  await expect(page.getByLabel('Timeline range',{exact:true})).toHaveValue('604800000')
  await expect(page.getByLabel('Timeline zoom',{exact:true})).toHaveValue('43200000')
  await expect(page.getByLabel('Search workflows, groups or jobs',{exact:true})).toHaveValue('PYMT')
  await expect(page.getByLabel('Filter workflow group',{exact:true})).toHaveValue('LOAD')
  await expect(page.locator('.ot-job')).toHaveCount(2)
  await expect.poll(async()=>Math.abs((await page.locator('.ot-viewport').evaluate(node=>node.scrollLeft))-x)).toBeLessThan(2)
  await expect(dialog()).toHaveCount(0)
  await shortBar().click()
  await dialog().getByRole('button',{name:'Show DAG run',exact:true}).click()
  await expect(page.getByRole('heading',{name:'DAG Run',exact:true})).toBeVisible()
  request=requests.filter(req=>req.path.endsWith('/dag')).at(-1)
  if(request.query.runId!==shortId || request.query.jobId!==dbt) throw Error('DAG used wrong run/job')
  await page.getByRole('button',{name:'← Back to monitor',exact:true}).click()
  await expect(page.getByLabel('Timeline zoom',{exact:true})).toHaveValue('43200000')
  await expect(page.locator('.ot-window')).toContainText('displayed')
  await page.locator(`[data-execution-id="${shortId}"]`).click()
  await dialog().getByRole('button',{name:'Show DAG run',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Workflow DAG Run',exact:true})).toBeVisible()
  request=requests.filter(req=>req.path.endsWith('/dag')).at(-1)
  if(request.query.runId!==shortId || request.query.jobId) throw Error('Workflow DAG incorrectly scoped to job/latest')
  await page.getByRole('button',{name:'← Back to monitor',exact:true}).click()
  await shortBar().click()
  await dialog().getByRole('button',{name:'Preview DAG',exact:true}).click()
  await expect(page.getByRole('heading',{name:'DAG Preview',exact:true})).toBeVisible()
  if(!requests.some(req=>req.path.endsWith('/jobs/'+dbt+'/dag-preview'))) throw Error('Preview not scoped to configured dbt job')
  await page.getByRole('button',{name:'Close dialog',exact:true}).click()
  await expect(dialog()).toBeVisible()
  await dialog().getByRole('button',{name:'Execution history',exact:true}).click()
  await expect(page.getByLabel('Filter history workflow',{exact:true})).toHaveValue(wfId)
  await expect(page.getByLabel('Filter history job',{exact:true})).toHaveValue(dbt)
  await page.getByRole('button',{name:'Expand all',exact:true}).click()
  await page.getByRole('button',{name:'Log for PYMT SDL',exact:true}).first().click()
  await expect(page.locator('.execution-log-page')).toBeVisible()
  await page.getByRole('button',{name:'← Back',exact:true}).click()
  await expect(page.getByLabel('Filter history job',{exact:true})).toHaveValue(dbt)
  await page.getByRole('button',{name:'← Monitor',exact:true}).click()
  await expect(page.getByLabel('Timeline zoom',{exact:true})).toHaveValue('43200000')
  await shortBar().click()
  await dialog().getByRole('button',{name:'Edit workflow',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Edit workflow',exact:true})).toBeVisible()
  await expect(page.getByLabel('Workflow name',{exact:true})).toHaveValue('PYMT LOAD')
  await page.getByRole('button',{name:'Close dialog',exact:true}).click()
  await page.getByRole('button',{name:'← Monitor',exact:true}).click()
  await expect(page.getByLabel('Timeline zoom',{exact:true})).toHaveValue('43200000')
  await shortBar().click()
  await dialog().getByRole('button',{name:'Dependencies',exact:true}).click()
  await expect(page.getByLabel('Search dependency configuration',{exact:true})).toHaveValue('PYMT LOAD')
  await page.getByRole('button',{name:'← Monitor',exact:true}).click()
  await shortBar().click()
  await dialog().getByRole('button',{name:'Trace relations',exact:true}).click()
  await expect(dialog()).toHaveCount(0)
  await expect(page.locator('.ot-connection-highlight')).toHaveCount(1)
  await page.locator('[data-execution-id="sql-run"]').click()
  await dialog().getByRole('button',{name:'Show workflow DAG run',exact:true}).click()
  await expect(page.locator('.dag-page')).toBeVisible()
  request=requests.filter(req=>req.path.endsWith('/dag')).at(-1)
  if(request.query.runId!==currentId || request.query.jobId) throw Error('SQL run did not open its full workflow execution DAG')
  await page.getByRole('button',{name:'← Back to monitor',exact:true}).click()
  await page.locator('[data-execution-id="pending-dbt"]').click()
  await expect(dialog().getByRole('button',{name:'Show DAG run',exact:true})).toBeDisabled()
  await page.keyboard.press('Escape')
  await shortBar().click()
  await dialog().getByRole('button',{name:'Workflow controls',exact:true}).click()
  await expect(page.locator('.om-monitor-table')).toBeVisible()
  await expect(page.locator('.om-children')).toBeVisible()
  await page.getByRole('button',{name:'Actions for workflow PYMT LOAD',exact:true}).click()
  await expect(page.locator('.om-action-options').getByRole('button',{name:'Disable schedule',exact:true})).toBeVisible()
  await expect(page.locator('.om-action-options').getByRole('button',{name:'Disable workflow',exact:true})).toBeVisible()
})
